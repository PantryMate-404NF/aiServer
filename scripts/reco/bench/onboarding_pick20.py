def _cat_index() -> dict[str, str]:
    """재료명 → category_path.

    🔴 이게 없으면 카테고리 기본값을 못 타서 overrides 38종 말고는 전부 0 벡터가 된다.
    """
    with (ROOT / "seeds/ingredient.csv").open(encoding="utf-8") as f:
        return {r["name"]: r["category_path"] for r in csv.DictReader(f)}


def build() -> tuple[dict[str, dict], set[str]]:
    """후보 전부의 flavor 를 재료에서 계산한다. (메뉴맵, 사전에 없는 재료)"""
    ft, cat = FlavorTable.from_seeds(), _cat_index()
    out, unknown = {}, set()
    for name, fam, items in MENUS:
        vecs = []
        for ing, role in items:
            if ing not in cat:
                unknown.add(ing)
            vecs.append((ft.of(ing, cat.get(ing)), role))
        out[name] = {"name": name, "family": fam,
                     "flavor": [round(x, 2) for x in aggregate(vecs, mode="role_w")],
                     "items": items}
    return out, unknown


def _dist(a: list[float], b: list[float]) -> float:
    return math.dist(a, b)


def check(m: dict[str, dict], unknown: set[str]) -> list[str]:
    """정본 목록이 쓸 만한지 본다. 반환값이 비어 있어야 통과."""
    bad: list[str] = []
    if unknown:
        bad.append(f"시드 사전에 없는 재료 {len(unknown)}종: {', '.join(sorted(unknown))}")

    for label, names in (("PRESENTED", PRESENTED), ("RESERVE", RESERVE)):
        if len(names) != 20:
            bad.append(f"{label} 가 {len(names)}개다 (20 이어야 한다)")
        miss = [n for n in names if n not in m]
        if miss:
            bad.append(f"{label} 에 MENUS 없는 이름: {', '.join(miss)}")
    dup = set(PRESENTED) & set(RESERVE)
    if dup:
        bad.append(f"제시·교체 양쪽에 있는 메뉴: {', '.join(sorted(dup))}")

    rows = [m[n] for n in PRESENTED if n in m]
    if rows:
        # 🔴 양념(S)이 없으면 맛 벡터가 밋밋해져 측정 도구로 못 쓴다.
        flat = [r["name"] for r in rows if not any(role is S for _, role in r["items"])]
        if flat:
            bad.append(f"양념(S)이 없는 메뉴: {', '.join(flat)}")
        over = {f: c for f, c in Counter(r["family"] for r in rows).items()
                if c > CAP.get(f, 99)}
        if over:
            bad.append(f"계열 상한 초과: {over} (상한 {CAP})")
        # 어느 축도 대표하지 못하면 그 20개는 그 축을 못 잰다.
        for i, a in enumerate(AX):
            if max(r["flavor"][i] for r in rows) < 0.35:
                bad.append(f"{a} 축 최고가 0.35 미만 — 그 취향을 가려낼 수 없다")
    return bad


def report(m: dict[str, dict]) -> None:
    for label, names in (("제시 20", PRESENTED), ("교체 후보 20", RESERVE)):
        rows = [m[n] for n in names if n in m]
        print(f"\n── {label}  {dict(Counter(r['family'] for r in rows))}")
        for i, a in enumerate(AX):
            v = [r["flavor"][i] for r in rows]
            top = max(rows, key=lambda r: r["flavor"][i])
            print(f"   {a:5} 최고 {max(v):.2f} ({top['name']})   0.25 이상 {sum(1 for x in v if x >= 0.25):2}개")
        # 가장 닮은 한 쌍 — 너무 가까우면 둘 중 하나는 정보를 안 준다
        pairs = [(_dist(a["flavor"], b["flavor"]), a["name"], b["name"])
                 for i, a in enumerate(rows) for b in rows[i + 1:]]
        d, x, y = min(pairs)
        print(f"   가장 닮은 쌍: {x} ↔ {y} ({d:.2f})")


def suggest(m: dict[str, dict]) -> None:
    """max-min 다양성 + 계열 상한으로 20개를 뽑아 **화면에만** 보여준다.

    🔴 파일을 쓰지 않는다. 사람의 판단(인지도·도메인 적합성)이 빠져 있어서
       그대로 쓰면 손으로 고친 것이 되돌아간다.
    """
    c = list(m.values())
    used: Counter[str] = Counter()
    sel = [max(range(len(c)), key=lambda i: sum(c[i]["flavor"]))]
    used[c[sel[0]]["family"]] += 1
    while len(sel) < 20:
        best, bd = None, -1.0
        for i in range(len(c)):
            if i in sel or used[c[i]["family"]] >= CAP.get(c[i]["family"], 99):
                continue
            dd = min(_dist(c[i]["flavor"], c[j]["flavor"]) for j in sel)
            if dd > bd:
                best, bd = i, dd
        if best is None:
            break
        sel.append(best)
        used[c[best]["family"]] += 1
    algo = {c[i]["name"] for i in sel}
    cur = set(PRESENTED)
    print(f"\n── 재선정안 (참고용 · 파일은 안 건드린다)")
    print(f"   현행과 일치 {len(algo & cur)}/20")
    print(f"   알고리즘만 넣음: {', '.join(sorted(algo - cur)) or '없음'}")
    print(f"   현행에만 있음  : {', '.join(sorted(cur - algo)) or '없음'}")
    print("   🔴 그대로 쓰지 말 것 — 인지도·도메인 판단이 빠져 있다.")


def emit(m: dict[str, dict]) -> str:
    def block(title: str, names: list[str], key: str) -> list[str]:
        out = [f"# ── {title} ─────────────", f"{key}:"]
        for n in names:
            r = m[n]
            fl = "[" + ", ".join(f"{x:.2f}" for x in r["flavor"]) + "]"
            it = "[" + ", ".join(f"[{ing}, {LETTER[role]}]"
                                 for ing, role in r["items"]) + "]"
            out += [f"  - {{name: {n}, family: {r['family']}, flavor: {fl},",
                    f"     items: {it}}}"]
        return out + [""]

    head = [
        "# 온보딩 제시 레시피 — 제시 20 · 교체 후보 20 (02 I-8 · 04)",
        "#",
        "# 🔴 손으로 고치지 않는다. 생성물이다:",
        "#      .venv/bin/python scripts/reco/bench/onboarding_pick20.py",
        "#    목록을 바꾸려면 그 스크립트의 PRESENTED·RESERVE 를 고친다.",
        "#",
        "# `taste_vec = 고른 레시피의 flavor_vec 평균` 이므로 이 목록이 곧 측정 도구다.",
        "#",
        "# flavor 는 items 에서 계산된다 (p5_flavor.aggregate, mode='role_w').",
        "# 시드(seeds/ingredient_flavor.yaml)가 바뀌면 값도 바뀐다 — 재생성이 정본이다.",
        "# 09-04 에 실제로 어긋난 것을 발견했다: 돈까스 기름짐 0.45 → 0.69.",
        "#",
        "# 🔴 재료 구성은 요리 상식이지 실측이 아니다. 리포트에 '실측'으로 쓰지 말 것.",
        "# 🔴 items 의 재료명은 seeds/ingredient.csv 536종에 있는 것만. E 주 · S 양념 · O 선택",
        "#",
        "# 사람이 읽는 판:  docs/reco/draft/25_온보딩_음식목록.md",
        "",
        "version: 2",
        f"axes: [{', '.join(AX)}]",
        "",
    ]
    return "\n".join(head
                     + block("제시 20 (유저에게 보여줄 것). picks 는 이 배열의 인덱스다",
                             PRESENTED, "presented")
                     + block("교체 후보 20 (제시하지 않는다. 바꿔 끼울 때 쓴다)",
                             RESERVE, "reserve"))


def main() -> int:
    argv = sys.argv[1:]
    m, unknown = build()

    bad = check(m, unknown)
    if bad:
        print("🔴 검사 실패")
        for b in bad:
            print(f"   · {b}")
        return 1
    print("✅ 검사 통과 — 재료명 · 중복 · 계열 상한 · 축 커버리지")
    report(m)

    if "--suggest" in argv:
        suggest(m)
    if "--check" in argv or "--suggest" in argv:
        print("\n(파일을 쓰지 않았다)")
        return 0

    out = ROOT / "seeds/onboarding_recipes.yaml"
    out.write_text(emit(m), encoding="utf-8")
    print(f"\n✓ {out.relative_to(ROOT)} — 제시 {len(PRESENTED)} · 교체 후보 {len(RESERVE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
